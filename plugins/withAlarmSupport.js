const {
  AndroidConfig,
  withAndroidManifest,
  withDangerousMod,
  withMainApplication,
  withSettingsGradle,
} = require('expo/config-plugins');
const fs = require('node:fs');
const path = require('node:path');

/**
 * Everything a real alarm needs on Android that app.json cannot express.
 *
 * Four separate things, and all four are required — missing any one of them
 * leaves you with a notification that happens to be loud:
 *
 *  1. USE_FULL_SCREEN_INTENT, so the notification may launch an activity
 *     instead of only showing a banner.
 *  2. showWhenLocked + turnScreenOn on the main activity, so that activity can
 *     appear over the lock screen and wake the display. Without these the
 *     full-screen intent fires into a screen nobody can see.
 *  3. The alarm tone copied into res/raw, which is the only place Android will
 *     look for a notification channel sound.
 *  4. A notification channel that plays on the ALARM stream. See
 *     `withAlarmChannel` below.
 *
 * Note on Android 14+: declaring USE_FULL_SCREEN_INTENT is no longer enough.
 * Only calling and alarm-clock apps are granted it at install; everything else
 * has to be allowed by the user under Special app access. The app asks for
 * that at runtime — see `src/notifications/service.ts`.
 */

const ALARM_SOUND = 'alarm_tone.wav';

function withFullScreenIntentPermission(config) {
  return AndroidConfig.Permissions.withPermissions(config, [
    'android.permission.USE_FULL_SCREEN_INTENT',
  ]);
}

function withLockScreenActivity(config) {
  return withAndroidManifest(config, (cfg) => {
    const activity = AndroidConfig.Manifest.getMainActivityOrThrow(cfg.modResults);
    activity.$['android:showWhenLocked'] = 'true';
    activity.$['android:turnScreenOn'] = 'true';
    // An alarm must not be dismissed by the task switcher.
    activity.$['android:excludeFromRecents'] = 'false';
    return cfg;
  });
}

function withAlarmSound(config) {
  return withDangerousMod(config, [
    'android',
    (cfg) => {
      const source = path.join(cfg.modRequest.projectRoot, 'assets', 'sounds', ALARM_SOUND);
      if (!fs.existsSync(source)) {
        throw new Error(
          `withAlarmSupport: alarm tone missing at ${source}. ` +
            'The notification channel references it by name, so the build must not continue without it.',
        );
      }

      const rawDir = path.join(
        cfg.modRequest.platformProjectRoot,
        'app',
        'src',
        'main',
        'res',
        'raw',
      );
      fs.mkdirSync(rawDir, { recursive: true });
      fs.copyFileSync(source, path.join(rawDir, ALARM_SOUND));
      return cfg;
    },
  ]);
}

/**
 * One channel per sound/vibration combination, because on Android 8+ the
 * channel, not the notification, decides both — a reminder's "sound" and
 * "vibrate" switches only mean something if each combination has a channel.
 *
 * Shared with `src/notifications/service.ts`, which picks between them.
 * Channels are immutable once created, so changing a channel's settings means
 * a new id.
 */
const ALARM_CHANNELS = require('../src/notifications/alarm-channels.json');

/**
 * Notifee creates channels on the notification stream, and offers no way to
 * change that. On the notification stream, a phone on vibrate or silent plays
 * nothing — so the alarm arrives as a silent banner, which is exactly the
 * failure this app exists to prevent.
 *
 * An alarm clock plays on the ALARM stream instead: its own volume, unaffected
 * by vibrate and silent mode, and let through by Do Not Disturb's default
 * "allow alarms". Android only lets a channel choose its stream at creation,
 * so the channels are created natively at app start, before any JS runs.
 * Notifee then posts into them by id.
 */
function alarmChannelSource(packageName) {
  const calls = ALARM_CHANNELS.map(
    (c) => `    create(manager, sound, "${c.id}", "${c.name}", ${c.sound}, ${c.vibrate})`,
  ).join('\n');

  return `package ${packageName}

import android.app.Notification
import android.app.NotificationChannel
import android.app.NotificationManager
import android.content.Context
import android.media.AudioAttributes
import android.net.Uri
import android.os.Build

/** Generated by plugins/withAlarmSupport.js — edit it there, not here. */
object AlarmChannel {
  fun ensure(context: Context) {
    if (Build.VERSION.SDK_INT < Build.VERSION_CODES.O) return
    val manager = context.getSystemService(NotificationManager::class.java) ?: return
    val sound = Uri.parse("android.resource://\${context.packageName}/\${R.raw.alarm_tone}")
${calls}
  }

  private fun create(
    manager: NotificationManager,
    sound: Uri,
    id: String,
    name: String,
    withSound: Boolean,
    withVibration: Boolean,
  ) {
    if (Build.VERSION.SDK_INT < Build.VERSION_CODES.O) return
    if (manager.getNotificationChannel(id) != null) return

    val channel = NotificationChannel(id, name, NotificationManager.IMPORTANCE_HIGH).apply {
      description = "Rings when an eye drop is due."
      if (withSound) {
        setSound(
          sound,
          AudioAttributes.Builder()
            .setUsage(AudioAttributes.USAGE_ALARM)
            .setContentType(AudioAttributes.CONTENT_TYPE_SONIFICATION)
            .build(),
        )
      } else {
        setSound(null, null)
      }
      enableVibration(withVibration)
      // Wait, vibrate, wait, vibrate... — starts at once, long pulses.
      if (withVibration) vibrationPattern = longArrayOf(1, 800, 400, 800, 400, 800)
      lockscreenVisibility = Notification.VISIBILITY_PUBLIC
      // Honoured only once the user grants Do Not Disturb access.
      setBypassDnd(true)
    }
    manager.createNotificationChannel(channel)
  }
}
`;
}

function withAlarmChannel(config) {
  const packageName = config.android?.package;
  if (!packageName) {
    throw new Error('withAlarmSupport: android.package must be set in app.json.');
  }

  config = withDangerousMod(config, [
    'android',
    (cfg) => {
      const dir = path.join(
        cfg.modRequest.platformProjectRoot,
        'app',
        'src',
        'main',
        'java',
        ...packageName.split('.'),
      );
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'AlarmChannel.kt'), alarmChannelSource(packageName));
      return cfg;
    },
  ]);

  return withMainApplication(config, (cfg) => {
    const call = 'AlarmChannel.ensure(this)';
    if (cfg.modResults.contents.includes(call)) return cfg;
    if (!cfg.modResults.contents.includes('super.onCreate()')) {
      throw new Error('withAlarmSupport: could not find super.onCreate() in MainApplication.');
    }
    cfg.modResults.contents = cfg.modResults.contents.replace(
      'super.onCreate()',
      `super.onCreate()\n    ${call}`,
    );
    return cfg;
  });
}

/**
 * Notifee's own build.gradle applies `io.invertase.gradle.build`, a Gradle
 * plugin published only to the Gradle Plugin Portal. Expo's generated
 * settings.gradle declares no pluginManagement repositories, and even with the
 * Portal reachable, resolution through a rate-limited proxy fails
 * intermittently — Gradle reports a 429 as "plugin not found".
 *
 * The plugin is three small files with no transitive dependencies, so they
 * are vendored under `vendor/maven/` and searched first. That makes this step
 * independent of the network entirely, and reproducible for anyone who clones
 * the repo. The Portal stays in the list as a fallback.
 */
function withPluginRepositories(config) {
  return withSettingsGradle(config, (cfg) => {
    if (cfg.modResults.contents.includes('vendor/maven')) return cfg;

    cfg.modResults.contents = cfg.modResults.contents.replace(
      'pluginManagement {',
      `pluginManagement {
  repositories {
    // Vendored io.invertase.gradle.build for @notifee/react-native.
    maven { url uri("\${settingsDir}/../vendor/maven") }
    gradlePluginPortal()
    google()
    mavenCentral()
  }
`,
    );
    return cfg;
  });
}

module.exports = function withAlarmSupport(config) {
  return withPluginRepositories(
    withAlarmChannel(
      withAlarmSound(withLockScreenActivity(withFullScreenIntentPermission(config))),
    ),
  );
};
